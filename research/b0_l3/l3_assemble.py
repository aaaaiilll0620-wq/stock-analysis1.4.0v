# --- per-security precomputation -------------------------------------------------

class SecuritySeries:
    """Everything a period lookup needs, computed once over the covered history.

    Rolling quantities are computed here rather than at lookup time because the
    frozen definitions do not depend on the as-of: C-25's ADV20 is a mean over
    20 OBSERVED sessions and C-26's sigma20d is the SD of 20 log returns, both
    bounded by the current listing spell (O-G).
    """

    __slots__ = ("sid", "dates", "pos", "close", "open_", "adj", "adv20",
                 "sigma20", "month_end", "spells", "unresolved")

    def __init__(self, sid, dates, close, open_, volume, factors,
                 unresolved_from, spells, sigma_at=()):
        self.sid = sid
        self.dates = dates
        self.pos = {d: i for i, d in enumerate(dates)}
        self.close = close
        self.open_ = open_
        self.adj = adjusted_closes(dates, close, factors)
        self.unresolved = tuple(unresolved_from or ())
        self.spells = spells

        self.adv20 = _rolling_mean(close * volume, ADV_SESSIONS)
        self.sigma20 = _rolling_sigma(self.adj, SIGMA_SESSIONS, sigma_at)

        me = {}
        for i, d in enumerate(dates):
            me[d[:7]] = i           # last observed session of each calendar month
        self.month_end = me

    def unresolved_at(self, as_of):
        """C-50/R8 bounded by as_of: the latest broken boundary already in force."""
        i = bisect.bisect_right(self.unresolved, as_of) - 1
        return self.unresolved[i] if i >= 0 else None

    def spell_start(self, as_of):
        i = bisect.bisect_right(self.spells, as_of) - 1
        return self.spells[i] if i >= 0 else None


def _rolling_mean(values, n):
    import numpy as np

    out = np.full(len(values), np.nan)
    if len(values) >= n:
        c = np.cumsum(np.insert(values, 0, 0.0))
        out[n - 1:] = (c[n:] - c[:-n]) / n
    return out


def _rolling_sigma(adj, n, at):
    """C-26 sigma20d, evaluated at the sessions a decision actually stands on.

    `compute_sigma20d` is CALLED rather than reimplemented — a second standard
    deviation in an assembler is exactly the quiet divergence M-1 exists to stop
    — but only at the as-of positions, because the other millions of
    evaluations would be arithmetic nobody reads.
    """
    import numpy as np

    out = np.full(len(adj), np.nan)
    for i in at:
        if i >= n:
            v = compute_sigma20d(list(adj[i - n:i + 1]))
            out[i] = np.nan if v is None else v
    return out


def build_series(px, cal, factors, unresolved, status_idx, as_ofs=()):
    calpos = {d: i for i, d in enumerate(cal)}
    out = {}
    for sid, g in px.groupby("stock_id", sort=True):
        dates = g["date"].tolist()
        close = g["close"].to_numpy(dtype=float)
        open_ = g["open"].to_numpy(dtype=float)
        vol = g["volume_shares"].to_numpy(dtype=float)
        first, last = dates[0], dates[-1]
        expected = cal[calpos[first]: calpos[last] + 1] if first in calpos else dates
        priced = set(dates)

        def explained(s_first, _sid=sid):
            return known_status_at(status_idx, _sid, s_first) != "listed"

        spells = spell_starts(expected, priced,
                              lambda s_first: explained(s_first)) or [dates[0]]
        pos = {d: i for i, d in enumerate(dates)}
        sigma_at = [pos[a] for a in as_ofs if a in pos]
        out[sid] = SecuritySeries(sid, dates, close, open_, vol,
                                  factors.get(sid, ()), unresolved.get(sid, ()),
                                  spells, sigma_at)
    return out


