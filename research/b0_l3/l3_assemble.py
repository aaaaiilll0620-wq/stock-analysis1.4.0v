def assert_both_price_legs_are_declared(run_dir: str) -> dict:
    """§2.8.3's lineage has two halves, and a leaf must declare both.

    The actionable form of the floor problem. Measured on the 2026-03 state
    while only the 2019+ leg was declared: 1,706 of 1,958 spell starts MOVED,
    most of them to 2019-01-02 — the corpus edge wearing a listing date.

    ⚠ BOTH ABSENCES ARE NAMED, because only one of them used to be. This guard
    checked the pre-2019 half and let the other fall through to `read_prices`,
    which builds the archive leg out of `frames[1:]` and therefore reached
    `pandas.concat([])`. Reproduced on a leaf carrying the cache leg alone:

        ValueError: No objects to concatenate      l3_readers.py:421

    Same class of absence as the one above, arriving as a library traceback that
    names neither the leaf, nor the leg, nor the run — while the sibling case
    names all three. An operator cannot act on the first message and can act on
    the second, and which one they get was decided by which half went missing.
    """
    from l3_readers import consumed_entries
    from source_ownership_manifest import LEAF_FILENAME, load_leaf

    leaf = load_leaf(os.path.join(run_dir, LEAF_FILENAME % "prices"))
    legs = collections.Counter(e.get("leg") or "unlabelled"
                               for e in consumed_entries(leaf))
    if LEG_PRE_2019 not in legs:
        raise AssemblyError(
            "abort: the prices leaf declares no pre-2019 leg (legs present: "
            "%s). §2.8.3 splits the price lineage at 2019-01-01 and the halves "
            "live in different trees; with only the later half declared, every "
            "listing spell for a security already listed in 2018 opens at the "
            "first covered session." % dict(legs))
    if LEG_2019_PLUS not in legs:
        raise AssemblyError(
            "abort: the prices leaf declares no 2019+ leg (legs present: %s). "
            "§2.8.3 splits the price lineage at 2019-01-01 and the halves live "
            "in different trees; with only the earlier half declared the price "
            "frame stops at 2018-12-31, so the decision date carries no mark, "
            "no ADV20 and no sigma20d for any security, and the §6.5 execution "
            "session has no opening price at all. An entry that carries no "
            "`leg` is not this half: `read_prices` sends every unlabelled entry "
            "down the 2019+ archive path, which is the declaration this leaf "
            "did not make." % dict(legs))
    return dict(legs)


# --- C-50 / C-51 · the adjusted price series ------------------------------------

def adjustment_plan(ledger, bonus_panel, cal):
    """(factors, unresolved_from) per security.

    `factors`   : ascending [(boundary_session, multiplier)] for every eligible
                  event whose holder multiplier is admissible.
    `unresolved`: ASCENDING boundaries of eligible events whose multiplier is
                  not reconstructible. Prices strictly before such a boundary
                  cannot be put on a comparable unit basis, so they are NA
                  (C-50/R8) rather than silently left unadjusted.

                  A LIST rather than a single latest boundary, because the
                  applicable one depends on as_of: an event that has not
                  happened yet cannot have broken a past window, and collapsing
                  the list to its maximum would let a 2026 event blank a 2014
                  momentum. That is look-ahead, and it is the defect this shape
                  exists to avoid.
    """
    bonus = {(str(r.stock_id), str(r.market_effective_session)): r
             for r in bonus_panel.itertuples()}
    calset = set(cal)
    factors = collections.defaultdict(list)
    unresolved = collections.defaultdict(list)
    stats = collections.Counter()
    for row in ledger:
        kind = row["kind"]
        try:
            klass = assert_kind_classified(kind)
        except UnreconstructibleAdjustment:
            stats["kind_unclassified"] += 1
            raise
        if klass != "eligible":
            continue
        sid, ex = str(row["stock_id"]), row["ex_or_effective_date"]
        if not ex:
            continue
        # C-50/R4: a boundary that is not a session resolves forward to the
        # first one, which is that clause's own rule.
        b = ex if ex in calset else next((s for s in cal if s > ex), None)
        if b is None:
            continue
        rec = dict(row)
        if kind == "stock_dividend":
            hit = bonus.get((sid, ex))
            if hit is not None and hit.disposition == "OFFICIAL_BONUS_RATE":
                rec["bonus_shares_per_1000"] = hit.bonus_shares_per_1000
            elif hit is not None and hit.disposition == \
                    "NOT_APPLICABLE_TO_B0_MARKET_HISTORY":
                # C-51/R2: B0 has no market history there to adjust, and this is
                # NOT a missing multiplier. It must not poison later windows.
                stats["not_applicable"] += 1
                continue
        try:
            m = holder_multiplier(rec)
        except ShareUnitAdjustmentError:
            stats["unresolved"] += 1
            unresolved[sid].append(b)
            continue
        stats["resolved_" + kind] += 1
        factors[sid].append((b, float(m)))
    for sid in factors:
        factors[sid].sort()
    for sid in unresolved:
        unresolved[sid].sort()
    return factors, dict(unresolved), stats


def adjusted_closes(dates, closes, factors):
    """C-50/R3: `adjusted = raw / m` for every price BEFORE each boundary."""
    import numpy as np

    if not factors:
        return closes
    out = np.array(closes, dtype=float)
    for boundary, m in factors:
        i = bisect.bisect_left(dates, boundary)
        if i:
            out[:i] /= m
    return out


