def _earliest_required_month_end(cal, as_of: str) -> str:
    """The session that ends the oldest month `month_end_prices` reaches.

    The producer fixes WHICH month; only the calendar knows which session ends
    it. A month with no session at all is an abort rather than a shifted window:
    silently sliding to the next month is how a bonus window stops covering the
    reach it exists to cover.
    """
    month = lsp.earliest_required_month_end_month(as_of)
    sessions = [s for s in cal if s[:7] == month]
    if not sessions:
        raise AssemblyError(
            "abort: the declared calendar has no session in %s, the oldest month "
            "the %d-month month-end reach needs from as_of %s (§19.2)"
            % (month, MONTH_ENDS_REQUIRED, as_of))
    return max(sessions)


def price_coverage_floor(px) -> str:
    """The first session the price frame actually covers, from the data."""
    if px.empty:
        raise AssemblyError("abort: the declared price sources yielded no rows")
    return str(px["date"].min())


