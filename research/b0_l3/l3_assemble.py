def status_index(status_rows):
    """stock_id -> [(available_from, effective_from, status)], ascending."""
    by = collections.defaultdict(list)
    for r in status_rows:
        by[str(r["stock_id"])].append(
            (r["available_from"] or r["effective_from"],
             r["effective_from"], r["status"]))
    for k in by:
        by[k].sort()
    return by


def known_status_tuple_at(idx, sid, session):
    """B0.6 · O-E-1: the status knowable at `session`, WITH its PIT dates.

    The status string alone was never sufficient: `PitPriceObservation` refuses
    a non-listed status that does not carry the date it became knowable, because
    a suspension filed after the close must not explain that day's missing price.
    Returning only the string is what left the canonical state unable to
    construct the frozen observability object at all — which is why B0.6 exists.

    `available_from` is the semantic dependency; `effective_from` is carried for
    diagnostics only and no rule consults it.
    """
    cur = ("listed", None, None)
    for avail, eff, st in idx.get(sid, ()):
        if str(avail) <= str(session) and str(eff) <= str(session):
            cur = (st, avail, eff)
    return cur


def known_status_at(idx, sid, session):
    return known_status_tuple_at(idx, sid, session)[0]


# --- O-G · listing spells --------------------------------------------------------

def spell_starts(sessions, priced, gap_explained):
    """Ascending spell starts for one security.

    A gap breaks the spell unless something knowable at its FIRST missing
    session explains it (O-G). Computed once over the covered history rather
    than per period: the same rule, evaluated the same way.
    """
    starts, run_start, cur = [], None, None
    for s in sessions:
        if s in priced:
            if cur is None:
                cur = s
                starts.append(s)
            elif run_start is not None and not gap_explained(s_first=run_start):
                cur = s
                starts.append(s)
            run_start = None
        elif cur is not None and run_start is None:
            run_start = s
    return starts


# A SPELL START IS A PROPERTY OF THE CORPUS, NOT OF THE SECURITY.
#
# `spell_starts` opens a spell at the first observed session, so a security
# already listed when the price span begins gets a spell start equal to the span
# floor. That is not an L3 artefact: measured at 2026-03, L2's sealed state says
# 1101 台泥's spell starts 2013-01-02, which is where `build_price_panel.
# panel_span()` starts — January of the year of `window_start` minus
# `lookback_L_months` — not where 台泥 listed.
#
# O-G's `opened_by` admits exactly two values and M-3 aborts on a third, so
# there is no vocabulary for "the corpus starts here". Widening it would be a
# specification change. What this module does instead is REPORT the count, so a
# reader of the receipt can see how many first observations are the span floor
# rather than a listing.
