# -*- coding: utf-8 -*-
"""Definition B · the ONE full `CanonicalDecisionInput` that exists pre-L2.

`portfolio[t]` is causally generated by executing t-1, so `full_input[t]` cannot
exist before t-1 has run. Exactly one period escapes that: period 1, whose
portfolio is not an execution output but the frozen opening state — B0 starts the
window holding nothing but `C_ref` in cash, read from the registry rather than
produced by running anything.

This builder therefore constructs period 1's full input and NOTHING ELSE. It
does not run the decision layer, and `build_period_t_full_input` exists only to
fail loudly for every t > 1, which is the property definition B actually asks to
be demonstrated.

ONE recorded seam. The frozen opening state is declared at `window_start`
(2014-07-31, the decision date), while §6.6 dates the canonical decision state at
`resolve_as_of(window_start)` = 2014-07-30. With no holdings the two describe the
same economic state, but they are not the same hashed object, and this builder
re-dates nothing silently: it records both and reports the divergence.

    python research/b0_materializer/build_period1_full_input.py
"""
