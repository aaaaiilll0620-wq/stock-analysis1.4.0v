def decision_periods(cal):
    """The 141 frozen decision months and their §6.6 as-of sessions."""
    months = pd.period_range(WINDOW_START[:7], WINDOW_END[:7], freq="M")
    if len(months) != WINDOW_MONTHS:
        raise SystemExit("the frozen window is %d months, got %d"
                         % (WINDOW_MONTHS, len(months)))
    out = []
    for m in months:
        dd = str(m.end_time.date())
        i = bisect.bisect_left(cal, dd)
        prior = [s for s in cal[max(0, i - 10):i] if s < dd]
        if not prior:
            raise SystemExit("§6.6: no completed session before %s" % dd)
        as_of = prior[-1]
        j = bisect.bisect_right(cal, dd)
        if j >= len(cal):
            raise SystemExit("§6.5: no execution session after %s" % dd)
        out.append({"decision_month": str(m), "decision_date": dd,
                    "as_of": as_of, "execution_date": cal[j]})
    return out


# --- O-B / O-E-1 · which gaps are explained -----------------------------------

def status_index(status_rows):
    """stock_id -> [(available_from, effective_from, status)], ascending."""
    by = collections.defaultdict(list)
    for r in status_rows:
        by[str(r["stock_id"])].append(
            (r["available_from"] or r["effective_from"],
             r["effective_from"], r["status"]))
    for k in by:
        by[k].sort()
    return by


def known_status_tuple_at(idx, sid, session):
    """B0.6 · O-E-1: the status knowable at `session`, WITH its PIT dates.

    The status string alone was never sufficient: `PitPriceObservation` refuses a
    non-listed status that does not carry the date it became knowable, because a
    suspension filed after the close must not explain that day's missing price.
    Returning only the string is what left the canonical state unable to
    construct the frozen observability object at all.

    `available_from` is the semantic dependency. `effective_from` is carried for
    diagnostics only and no rule consults it.
    """
    cur = ("listed", None, None)
    for avail, eff, st in idx.get(sid, ()):
        if str(avail) <= str(session) and str(eff) <= str(session):
            cur = (st, avail, eff)
    return cur


def known_status_at(idx, sid, session):
    """The status string alone, for callers that genuinely need only that."""
    return known_status_tuple_at(idx, sid, session)[0]


# --- O-G · listing spells, derived once over the whole history ----------------

def spell_starts(sessions, priced, gap_explained):
    """Ascending spell starts for one security.

    A gap breaks the spell unless something knowable at its FIRST missing
    session explains it (O-G). Computed once over full history rather than
    per period, which is the same rule evaluated the same way.
    """
    starts, run_start, cur = [], None, None
    pset = priced
    for s in sessions:
        if s in pset:
            if cur is None:
                cur = s
                starts.append(s)
            elif run_start is not None and not gap_explained(s_first=run_start):
                cur = s
                starts.append(s)
            run_start = None
        elif cur is not None and run_start is None:
            run_start = s
    return starts


# --- C-50 / C-51 · the adjusted price series ----------------------------------

def adjustment_plan(ledger, bonus_panel, cal):
    """(factors, unresolved_from) per security.

    `factors`  : ascending [(boundary_session, multiplier)] for every eligible
                 event whose holder multiplier is admissible.
    `unresolved`: ASCENDING boundaries of eligible events whose multiplier is not
                 reconstructible. Prices strictly before such a boundary cannot
                 be put on a comparable unit basis, so they are NA (C-50/R8)
                 rather than silently left unadjusted.

                 A LIST rather than a single latest boundary, because the
                 applicable one depends on as_of: an event that has not happened
                 yet cannot have broken a past window, and collapsing the list to
                 its maximum would let a 2026 event blank a 2014 momentum. That
                 is look-ahead, and it is the defect this shape exists to avoid.
    """
    bonus = {(str(r.stock_id), str(r.market_effective_session)): r
             for r in bonus_panel.itertuples()}
    calset = set(cal)
    factors = collections.defaultdict(list)
    unresolved = collections.defaultdict(list)
    stats = collections.Counter()
    for row in ledger:
        kind = row["kind"]
        try:
            klass = assert_kind_classified(kind)
        except UnreconstructibleAdjustment:
            stats["kind_unclassified"] += 1
            raise
        if klass != "eligible":
            continue
        sid, ex = str(row["stock_id"]), row["ex_or_effective_date"]
        if not ex:
            continue
        # R4: the market-effective session. A boundary that is not a session
        # resolves forward to the first one, which is C-50/R4's own rule.
        b = ex if ex in calset else next((s for s in cal if s > ex), None)
        if b is None:
            continue
        rec = dict(row)
        if kind == "stock_dividend":
            hit = bonus.get((sid, ex))
            if hit is not None and hit.disposition == "OFFICIAL_BONUS_RATE":
                rec["bonus_shares_per_1000"] = hit.bonus_shares_per_1000
            elif hit is not None and hit.disposition == \
                    "NOT_APPLICABLE_TO_B0_MARKET_HISTORY":
                # C-51/R2: B0 has no market history there to adjust, and this is
                # NOT a missing multiplier. It must not poison later windows.
                stats["not_applicable"] += 1
                continue
        try:
            m = holder_multiplier(rec)
        except ShareUnitAdjustmentError:
            stats["unresolved"] += 1
            unresolved[sid].append(b)
            continue
        stats["resolved_" + kind] += 1
        factors[sid].append((b, float(m)))
    for sid in factors:
        factors[sid].sort()
    for sid in unresolved:
        unresolved[sid].sort()
    return factors, dict(unresolved), stats


def adjusted_closes(dates, closes, factors):
    """C-50/R3: `adjusted = raw / m` for every price BEFORE each boundary."""
    if not factors:
        return closes
    out = np.array(closes, dtype=float)
    for boundary, m in factors:
        i = bisect.bisect_left(dates, boundary)
        if i:
            out[:i] /= m
    return out


