def financial_index(fin):
    """stock_id -> ascending [(release_date, quarter_key, row)] (§2.2)."""
    fin = fin.copy()
    fin["release_date"] = fin["release_date"].astype(str).str[:10]
    fin["date"] = fin["date"].astype(str).str[:10]
    fin["stock_id"] = fin["stock_id"].astype(str)
    fin = fin.sort_values(["stock_id", "release_date", "date"])
    by = collections.defaultdict(list)
    for r in fin.itertuples():
        by[r.stock_id].append(r)
    return by


def revenue_index(rev):
    rev = rev.copy()
    rev["release_date"] = rev["release_date"].astype(str).str[:10]
    rev["date"] = rev["date"].astype(str).str[:10]
    rev["stock_id"] = rev["stock_id"].astype(str)
    rev = rev.sort_values(["stock_id", "date"])
    by = collections.defaultdict(list)
    for r in rev.itertuples():
        by[r.stock_id].append((r.release_date, r.date, r.revenue))
    return by


def industry_index(ind):
    by = collections.defaultdict(list)
    for r in ind.itertuples():
        by[str(r.stock_id)].append(
            (str(r.effective_from), str(r.tse_ind_code),
             str(r.unresolved_from) if r.unresolved_from else None))
    for k in by:
        by[k].sort()
    return by


def industry_at(idx, sid, as_of):
    """§2.3 step function; UNRESOLVED from `unresolved_from` onward."""
    code = INDUSTRY_UNRESOLVED
    for eff, tse, unres in idx.get(sid, ()):
        if eff <= as_of:
            code = tse or INDUSTRY_UNRESOLVED
            if unres and unres <= as_of:
                code = INDUSTRY_UNRESOLVED
    return code


def _f(v):
    if v is None:
        return None
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    return None if x != x or not math.isfinite(x) else x


# --- per-security precomputation ----------------------------------------------

class SecuritySeries:
    """Everything a period lookup needs, computed once over full history.

    Rolling quantities are computed here rather than per period because the
    frozen definitions are the same at every as-of: C-25's ADV20 is a mean over
    20 OBSERVED sessions, C-26's sigma20d is the SD of 20 log returns, and both
    are bounded by the current listing spell (O-G). Recomputing them 141 times
    would be the same arithmetic with 141 chances to drift.
    """

    __slots__ = ("sid", "dates", "pos", "close", "open_", "adj", "adv20",
                 "sigma20", "month_end", "spells", "unresolved")

    def __init__(self, sid, dates, close, open_, volume, factors,
                 unresolved_from, spells, sigma_at=()):
        self.sid = sid
        self.dates = dates
        self.pos = {d: i for i, d in enumerate(dates)}
        self.close = close
        self.open_ = open_
        self.adj = adjusted_closes(dates, close, factors)
        self.unresolved = tuple(unresolved_from or ())
        self.spells = spells

        turnover = close * volume
        self.adv20 = _rolling_mean(turnover, ADV_SESSIONS)
        self.sigma20 = _rolling_sigma(self.adj, SIGMA_SESSIONS, sigma_at)

        # last observed session of each calendar month
        me = {}
        for i, d in enumerate(dates):
            me[d[:7]] = i
        self.month_end = me

    def unresolved_at(self, as_of):
        """C-50/R8 bounded by as_of: the latest broken boundary already in force."""
        i = bisect.bisect_right(self.unresolved, as_of) - 1
        return self.unresolved[i] if i >= 0 else None

    def spell_start(self, as_of):
        i = bisect.bisect_right(self.spells, as_of) - 1
        return self.spells[i] if i >= 0 else None


def _rolling_mean(values, n):
    out = np.full(len(values), np.nan)
    if len(values) >= n:
        c = np.cumsum(np.insert(values, 0, 0.0))
        out[n - 1:] = (c[n:] - c[:-n]) / n
    return out


def _rolling_sigma(adj, n, at):
    """C-26 sigma20d, evaluated at the sessions a decision actually stands on.

    `compute_sigma20d` is called rather than reimplemented — a second SD in the
    materializer is exactly the kind of quiet divergence M-1 exists to stop —
    but only at the 141 as-of positions, because the other 5.8M evaluations
    would be arithmetic nobody reads.
    """
    out = np.full(len(adj), np.nan)
    for i in at:
        if i >= n:
            v = compute_sigma20d(list(adj[i - n:i + 1]))
            out[i] = np.nan if v is None else v
    return out


def build_series(px, cal, factors, unresolved, status_idx, as_ofs=()):
    calpos = {d: i for i, d in enumerate(cal)}
    out = {}
    for sid, g in px.groupby("stock_id", sort=True):
        dates = g["date"].tolist()
        close = g["close"].to_numpy(dtype=float)
        open_ = g["open"].to_numpy(dtype=float)
        vol = g["volume_shares"].to_numpy(dtype=float)
        first, last = dates[0], dates[-1]
        expected = cal[calpos[first]: calpos[last] + 1] if first in calpos else dates
        priced = set(dates)

        def explained(s_first, _sid=sid):
            return known_status_at(status_idx, _sid, s_first) != "listed"

        spells = spell_starts(expected, priced,
                              lambda s_first: explained(s_first)) or [dates[0]]
        pos = {d: i for i, d in enumerate(dates)}
        sigma_at = [pos[a] for a in as_ofs if a in pos]
        out[sid] = SecuritySeries(sid, dates, close, open_, vol,
                                  factors.get(sid, ()), unresolved.get(sid, ()),
                                  spells, sigma_at)
    return out


