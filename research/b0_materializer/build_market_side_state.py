def _quarter_series(rows, as_of, field):
    """The last QUARTERS values of `field`, CALENDAR-QUARTER indexed (4.1a-R2).

    Published on or before as_of (2.2), then laid out on consecutive fiscal
    quarters with an explicit None for any quarter that has no published figure.
    Compressing the gap out is what makes `series[-5]` stop being four quarters
    before `series[-1]`: measured at period 1, 177 of 1,730 securities (10.23%)
    had a non-contiguous last-8, so eps_growth compared the wrong base period and
    the TTM sums spanned five calendar quarters for every one of them.
    """
    seen = {}
    for r in rows:
        if r.release_date > as_of:
            continue
        seen[pd.Period(r.date, freq="Q")] = getattr(r, field)
    if not seen:
        return ()
    last = max(seen)
    span = pd.period_range(end=last, periods=QUARTERS, freq="Q")
    return tuple(_f(seen.get(q)) for q in span)


def _latest_quarter_row(rows, as_of):
    best = None
    for r in rows:
        if r.release_date <= as_of and (best is None or (r.date, r.release_date) >
                                        (best.date, best.release_date)):
            best = r
    return best


def _monthly_revenue(rows, as_of):
    """MONTHS_REVENUE values, CALENDAR-MONTH indexed (4.1a-R2).

    `compute_revenue_yoy` reads `series[-1]` against `series[-13]`, so t-12 is
    only truly last year's same month if the index is consecutive months. Current
    measured impact of compressing is 0 of 1,647 securities - this is an
    invariant, not a correction, and it is cheapest to impose now.
    """
    seen = {}
    for rel, d, rev in rows:
        if rel <= as_of:
            seen[pd.Period(d[:7], freq="M")] = rev
    if not seen:
        return []
    last = max(seen)
    span = pd.period_range(end=last, periods=MONTHS_REVENUE, freq="M")
    return [_f(seen.get(m)) for m in span]


def _month_end_prices(ss, as_of, spell, unresolved):
    """14 month-end ADJUSTED closes, newest last. NA where the unit basis breaks."""
    months = pd.period_range(end=pd.Period(as_of[:7], freq="M"),
                             periods=MONTH_ENDS_REQUIRED, freq="M")
    out = []
    for m in months:
        key = str(m)
        i = ss.month_end.get(key)
        if i is None or ss.dates[i] > as_of:
            # the current month is bounded by as_of, not by its calendar end
            cand = [j for j, d in enumerate(ss.dates) if d[:7] == key and d <= as_of]
            i = cand[-1] if cand else None
        if i is None:
            out.append(None)
            continue
        d = ss.dates[i]
        if spell is not None and d < spell:
            out.append(None)              # O-G: a window may not cross a spell
        elif unresolved is not None and d < unresolved:
            out.append(None)              # C-50/R8: no comparable unit basis
        else:
            out.append(_f(ss.adj[i]))
    return out


def build_period(p, series, fin_idx, rev_idx, ind_idx, val_by_month,
                 status_idx, ca_by_sid, cal):
    as_of, exec_date = p["as_of"], p["execution_date"]
    window_start = str(pd.Period(as_of[:7], freq="M")
                       - (MONTH_ENDS_REQUIRED - 1))
    val = val_by_month.get(p["decision_month"], {})
    rows = []
    for sid, ss in series.items():
        i = ss.pos.get(as_of)
        if i is None:
            continue                       # not quoted at the decision point
        spell = ss.spell_start(as_of)
        if spell is None:
            continue
        si = ss.pos[spell]
        n_in_spell = i - si + 1
        unres = ss.unresolved_at(as_of)
        adv = ss.adv20[i]
        if n_in_spell < ADV_SESSIONS or not np.isfinite(adv):
            # NA is for a dependency that is genuinely unavailable: fewer than
            # the required observed sessions in this spell (O-G resets ADV20 at
            # the spell start), or a non-finite input.
            adv = None
        # B0.5 · R1/R2. An ADV20 of exactly 0 is NOT encoded as absence any more.
        # Twenty observed zero-volume sessions average to 0.0, which is a
        # liquidity OBSERVATION. The previous code dropped it, reasoning that
        # 4.2's floor rejects 0 anyway so the encoding "changes no eligibility
        # outcome" -- but 4.2 aborts on a MISSING adv20 before it ever reaches
        # the floor, which is exactly how B04DIAG-d5f34a5164a0e309 stopped on a
        # name quoted all year at a frozen price with no turnover.
        sig = ss.sigma20[i]
        if n_in_spell < SIGMA_SESSIONS + 1 or not np.isfinite(sig):
            sig = None
        elif unres is not None and ss.dates[max(0, i - SIGMA_SESSIONS)] < unres:
            sig = None                     # C-50/R8 reaches into the sigma window
        _status = known_status_tuple_at(status_idx, sid, as_of)
        j = ss.pos.get(exec_date)
        v = val.get(sid, {})
        frows = fin_idx.get(sid, ())
        latest = _latest_quarter_row(frows, as_of)
        mrev = _monthly_revenue(rev_idx.get(sid, ()), as_of)
        rows.append({
            "stock_id": sid,
            "mark": _f(ss.close[i]),
            "adv20": _f(adv),
            "sigma20d": _f(sig),
            "execution_open": _f(ss.open_[j]) if j is not None else None,
            "spell_start": spell,
            "known_status": _status[0],
            "status_available_from": _status[1],
            "status_effective_from": _status[2],
            "month_end_prices": _month_end_prices(ss, as_of, spell, unres),
            "monthly_revenue": [_f(x) for x in mrev],
            "net_income_by_quarter": list(_quarter_series(frows, as_of, "net_income")),
            "revenue_by_quarter": list(_quarter_series(frows, as_of, "revenue")),
            "gross_profit_by_quarter": list(_quarter_series(frows, as_of, "gross_profit")),
            "eps_by_quarter": list(_quarter_series(frows, as_of, "eps")),
            "period_end_equity": _f(getattr(latest, "equity", None)),
            "total_liabilities": _f(getattr(latest, "total_liabilities", None)),
            "total_assets": _f(getattr(latest, "total_assets", None)),
            "current_assets": _f(getattr(latest, "current_assets", None)),
            "current_liabilities": _f(getattr(latest, "current_liabilities", None)),
            "per_tse": _f(v.get("per_tse")),
            "pbr_tse": _f(v.get("pbr_tse")),
            "pit_industry": industry_at(ind_idx, sid, as_of),
            "corporate_action_events": [
                [e["kind"], e["ex_or_effective_date"], e["reconstructibility"]]
                for e in ca_by_sid.get(sid, ())
                if window_start <= e["ex_or_effective_date"] <= as_of],
        })
    return rows


# --- the hashed view -----------------------------------------------------------

def market_state_payload(p, rows):
    """The market side of `CanonicalDecisionInput.state_payload`, and only that.

    Deliberately absent: cash, shares, pending_exit, receivables and exposures.
    Definition B — those are causally generated by executing the previous period,
    so a market-side hash that included a placeholder for them would be a hash of
    a fabrication. `assert_market_state_is_portfolio_free` pins that.
    """
    return {
        "decision_month": p["decision_month"],
        "decision_date": p["decision_date"],
        "as_of": p["as_of"],
        "execution_date": p["execution_date"],
        "marks": {r["stock_id"]: r["mark"] for r in rows
                  if r["mark"] is not None and r["mark"] > 0},
        "adv20": {r["stock_id"]: r["adv20"] for r in rows if r["adv20"] is not None},
        "sigma20d": {r["stock_id"]: r["sigma20d"] for r in rows
                     if r["sigma20d"] is not None},
        "execution_prices": {r["stock_id"]: r["execution_open"] for r in rows
                             if r["execution_open"] is not None},
        "untradable": sorted(r["stock_id"] for r in rows
                             if r["known_status"] != "listed"),
        # B0.6. `build_input` now feeds the PIT status dates into the decision,
        # so they are decision inputs and the hashed view must bind them.
        # Leaving them out would let two states with different status dates hash
        # identically -- the same sealed-input sufficiency defect (C-55) this
        # repair exists to close, one field further down.
        #
        # Only non-listed rows carry information here: a listed row's dates are
        # consulted by no rule, and any listed/non-listed flip already moves
        # `untradable` above.
        "security_status": [
            {"stock_id": r["stock_id"], "known_status": r["known_status"],
             "status_available_from": r["status_available_from"],
             "status_effective_from": r["status_effective_from"]}
            for r in sorted(rows, key=lambda x: x["stock_id"])
            if r["known_status"] != "listed"],
        "listing_spells": [{"stock_id": r["stock_id"], "start": r["spell_start"]}
                           for r in sorted(rows, key=lambda x: x["stock_id"])],
        "pit_inputs": [
            {"stock_id": r["stock_id"],
             "net_income_by_quarter": r["net_income_by_quarter"],
             "revenue_by_quarter": r["revenue_by_quarter"],
             "gross_profit_by_quarter": r["gross_profit_by_quarter"],
             "eps_by_quarter": r["eps_by_quarter"],
             "period_end_equity": r["period_end_equity"],
             "total_liabilities": r["total_liabilities"],
             "total_assets": r["total_assets"],
             "current_assets": r["current_assets"],
             "current_liabilities": r["current_liabilities"],
             "monthly_revenue": r["monthly_revenue"],
             "month_end_prices": r["month_end_prices"],
             "per_tse": r["per_tse"],
             "pbr_tse": r["pbr_tse"],
             "pit_industry": r["pit_industry"]}
            for r in sorted(rows, key=lambda x: x["stock_id"])],
        "corporate_action_events": [
            {"stock_id": r["stock_id"], "events": r["corporate_action_events"]}
            for r in sorted(rows, key=lambda x: x["stock_id"])
            if r["corporate_action_events"]],
    }


LIST_COLUMNS = ("month_end_prices", "monthly_revenue", "net_income_by_quarter",
                "revenue_by_quarter", "gross_profit_by_quarter",
                "eps_by_quarter", "corporate_action_events")
SCALAR_COLUMNS = ("mark", "adv20", "sigma20d", "execution_open", "per_tse",
                  "pbr_tse", "period_end_equity", "total_liabilities",
                  "total_assets", "current_assets", "current_liabilities")


def rows_from_parquet(df):
    """The exact inverse of what `main` writes.

    Parquet round-trips a Python list of floats as a numpy array and `None` as
    NaN, so a naive read-back hashes differently from what was hashed. This is
    the ONE place that knows the round-trip, used by the rebuild check as well,
    so "it rebuilds identically" is a property of the artefact rather than of
    whoever wrote the reader.
    """
    rows = df.to_dict("records")
    for r in rows:
        r["stock_id"] = str(r["stock_id"])
        for k in LIST_COLUMNS:
            v = r[k]
            if v is None:
                r[k] = []
            elif k == "corporate_action_events":
                r[k] = [[str(x) for x in list(e)] for e in list(v)]
            else:
                r[k] = [_f(x) for x in list(v)]
        for k in SCALAR_COLUMNS:
            r[k] = _f(r[k])
        for k in ("spell_start", "known_status", "status_available_from",
                  "status_effective_from", "pit_industry"):
            r[k] = str(r[k])
    return rows


PORTFOLIO_FIELDS = ("cash", "shares", "pending_exit", "cash_dividend_receivable",
                    "stock_dividend_receivable", "exposures", "portfolio")


def assert_market_state_is_portfolio_free(payload):
    """Definition B, as a check rather than a comment."""
    leaked = [k for k in PORTFOLIO_FIELDS if k in payload]
    if leaked:
        raise SystemExit(
            "definition B: the market-side state carries portfolio fields %s. "
            "portfolio[t] is causally generated by executing t-1 and may not be "
            "invented here." % leaked)


def main() -> int:
    assert_not_writing_into_frozen_b0(OUTDIR)
    assert_not_writing_into_frozen_b0(MANIFEST)
    _log("lineage: %s  window %s .. %s (%d periods)"
         % (LINEAGE, WINDOW_START, WINDOW_END, WINDOW_MONTHS))
    os.makedirs(OUTDIR, exist_ok=True)
    _log("loading sealed sources ...")
    cal, px, ledger, status, bonus, val, fin, rev, ind = load_sources()
    periods = decision_periods(cal)
    _log("periods: %d  %s .. %s" % (len(periods), periods[0]["decision_month"],
                                    periods[-1]["decision_month"]))

    factors, unresolved, adj_stats = adjustment_plan(ledger, bonus, cal)
    _log("share-unit factors: %s" % dict(adj_stats))
    _log("securities with an unresolved eligible boundary: %d" % len(unresolved))

    status_idx = status_index(status)
    _log("deriving listing spells and rolling windows ...")
    series = build_series(px, cal, factors, unresolved, status_idx,
                          [p["as_of"] for p in periods])
    _log("securities with a price history: %d" % len(series))

    fin_idx = financial_index(fin)
    rev_idx = revenue_index(rev)
    ind_idx = industry_index(ind)
    val_by_month = {}
    for r in val.itertuples():
        val_by_month.setdefault(str(r.decision_month), {})[str(r.stock_id)] = {
            "per_tse": r.per_tse, "pbr_tse": r.pbr_tse}
    ca_by_sid = collections.defaultdict(list)
    for row in ledger:
        ca_by_sid[str(row["stock_id"])].append(row)

    manifest, built = [], 0
    for p in periods:
        rows = build_period(p, series, fin_idx, rev_idx, ind_idx, val_by_month,
                            status_idx, ca_by_sid, cal)
        if not rows:
            raise SystemExit("period %s produced no market-side state"
                             % p["decision_month"])
        payload = market_state_payload(p, rows)
        assert_market_state_is_portfolio_free(payload)
        sha = canonical_sha256(payload)
        out = os.path.join(OUTDIR, "%s.parquet" % p["decision_month"])
        assert_not_writing_into_frozen_b0(out)
        pd.DataFrame(rows).to_parquet(out, index=False)
        manifest.append({
            "decision_month": p["decision_month"],
            "decision_date": p["decision_date"],
            "as_of": p["as_of"],
            "execution_date": p["execution_date"],
            "securities": len(rows),
            "marks": len(payload["marks"]),
            "adv20": len(payload["adv20"]),
            "sigma20d": len(payload["sigma20d"]),
            "execution_prices": len(payload["execution_prices"]),
            "untradable": len(payload["untradable"]),
            "market_state_sha256": sha,
            "artefact": os.path.relpath(out, REPO).replace("\\", "/"),
        })
        built += 1
        if built % 20 == 0:
            _log("  built %d/%d  (%s: %d securities)"
                 % (built, len(periods), p["decision_month"], len(rows)))

    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=1)

    composed = "".join("%s:%s\n" % (m["decision_month"], m["market_state_sha256"])
                       for m in manifest)
    import hashlib
    composed_sha = hashlib.sha256(composed.encode()).hexdigest()
    receipt = {
        "lineage": LINEAGE,
        "artefact": os.path.relpath(OUTDIR, REPO).replace("\\", "/")
                    + "/<decision_month>.parquet",
        "manifest": os.path.relpath(MANIFEST, REPO).replace("\\", "/"),
        "builder": "research/b0_materializer/build_market_side_state.py",
        "clause": "definition A · %d market-side canonical states, pre-L2"
                  % WINDOW_MONTHS,
        "periods_built": built,
        "periods_required": WINDOW_MONTHS,
        "window": [WINDOW_START, WINDOW_END],
        "composed_market_state_sha256": composed_sha,
        "securities_min": min(m["securities"] for m in manifest),
        "securities_max": max(m["securities"] for m in manifest),
        "share_unit_adjustment": dict(adj_stats),
        "securities_with_unresolved_boundary": len(unresolved),
        "portfolio_side_materialized": False,
        "decision_layer_invoked": False,
        "performance_computed": False,
    }
    with open(RECEIPT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(receipt, fh, ensure_ascii=False, indent=1, sort_keys=True)

    _log("")
    _log("periods built            : %d/%d" % (built, WINDOW_MONTHS))
    _log("securities per period    : %d .. %d" % (receipt["securities_min"],
                                                  receipt["securities_max"]))
    _log("composed market-state sha: %s" % composed_sha)
    _log("wrote %s and %s" % (os.path.relpath(MANIFEST, REPO),
                              os.path.relpath(RECEIPT, REPO)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
